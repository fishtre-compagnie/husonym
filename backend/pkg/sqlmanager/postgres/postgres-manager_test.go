func Test_EscapePgColumns(t *testing.T) {
	require.Empty(t, EscapePgColumns(nil))
	require.Equal(
		t,
		EscapePgColumns([]string{"foo", "bar", "baz"}),
		[]string{`"foo"`, `"bar"`, `"baz"`},
	)
}

func Test_BuildPgTruncateStatement(t *testing.T) {
	stmt, err := BuildPgTruncateStatement(
		[]*sqlmanager_shared.SchemaTable{
			{Schema: "public", Table: "users"},
			{Schema: "bad name", Table: "C$@111"},
		},
	)
	require.NoError(t, err)
	require.Equal(
		t,
		"TRUNCATE \"public\".\"users\", \"bad name\".\"C$@111\" RESTART IDENTITY;",
		stmt,
	)
}

func Test_BuildPgTruncateCascadeStatement(t *testing.T) {
	actual, err := BuildPgTruncateCascadeStatement("public", "users")
	require.NoError(t, err)
	require.Equal(
		t,
		"TRUNCATE \"public\".\"users\" RESTART IDENTITY CASCADE;",
		actual,
	)
}

func Test_SequenceConfiguration(t *testing.T) {
	s := SequenceConfiguration{
		IncrementBy: 1,
		MinValue:    2,
		MaxValue:    5,
		StartValue:  2,
		CacheValue:  1,
		CycleOption: false,
	}
	require.Equal(
		t,
		"GENERATED BY DEFAULT AS IDENTITY ( INCREMENT BY 1 MINVALUE 2 MAXVALUE 5 START 2 CACHE 1 NO CYCLE )",
		s.ToGeneratedDefaultIdentity(),
	)
	require.Equal(
		t,
		"GENERATED ALWAYS AS IDENTITY ( INCREMENT BY 1 MINVALUE 2 MAXVALUE 5 START 2 CACHE 1 NO CYCLE )",
		s.ToGeneratedAlwaysIdentity(),
	)
}

func Test_BuildPgInsertIdentityAlwaysSql(t *testing.T) {
	t.Run("Basic insert query", func(t *testing.T) {
		input := "INSERT INTO users (id, name, email) VALUES (1, 'John', 'john@example.com')"
		expected := "INSERT INTO users (id, name, email) OVERRIDING SYSTEM VALUE VALUES(1, 'John', 'john@example.com')"
		result := BuildPgInsertIdentityAlwaysSql(input)
		require.Equal(t, expected, result)
	})

	t.Run("Insert query with multiple values", func(t *testing.T) {
		input := "INSERT INTO products (id, name, price) VALUES (1, 'Apple', 0.99), (2, 'Orange', 1.29)"
		expected := "INSERT INTO products (id, name, price) OVERRIDING SYSTEM VALUE VALUES(1, 'Apple', 0.99), (2, 'Orange', 1.29)"
		result := BuildPgInsertIdentityAlwaysSql(input)
		require.Equal(t, expected, result)
	})

	t.Run("Insert query with quoted values", func(t *testing.T) {
		input := "INSERT INTO quotes (id, text) VALUES (1, 'It''s a quote')"
		expected := "INSERT INTO quotes (id, text) OVERRIDING SYSTEM VALUE VALUES(1, 'It''s a quote')"
		result := BuildPgInsertIdentityAlwaysSql(input)
		require.Equal(t, expected, result)
	})

	t.Run("Insert query with parentheses in values", func(t *testing.T) {
		input := "INSERT INTO data (id, value) VALUES (1, '(nested) (parentheses)')"
		expected := "INSERT INTO data (id, value) OVERRIDING SYSTEM VALUE VALUES(1, '(nested) (parentheses)')"
		result := BuildPgInsertIdentityAlwaysSql(input)
		require.Equal(t, expected, result)
	})
}

// The override of an identity column is placed where the column list ends, whatever text the
// names and the values of the statement hold.
func Test_BuildPgInsertIdentityAlwaysSql_ColumnListEnd(t *testing.T) {
	cases := []struct{ name, input, expected string }{
		{
			"table name holding the text",
			`INSERT INTO "app"."a) VALUES (b" ("id") VALUES ($1)`,
			`INSERT INTO "app"."a) VALUES (b" ("id") OVERRIDING SYSTEM VALUE VALUES($1)`,
		},
		{
			"column name holding the text, named again after the values",
			`INSERT INTO "t" ("id", "x) VALUES (y") VALUES ($1, $2), ($3, $4) ON CONFLICT ("id") DO UPDATE SET "x) VALUES (y"=EXCLUDED."x) VALUES (y"`,
			`INSERT INTO "t" ("id", "x) VALUES (y") OVERRIDING SYSTEM VALUE VALUES($1, $2), ($3, $4) ON CONFLICT ("id") DO UPDATE SET "x) VALUES (y"=EXCLUDED."x) VALUES (y"`,
		},
		{
			"name holding a quote character and the text",
			`INSERT INTO "we""ird) VALUES (b" ("o'clock", "two$$dollars") VALUES ($1, $2)`,
			`INSERT INTO "we""ird) VALUES (b" ("o'clock", "two$$dollars") OVERRIDING SYSTEM VALUE VALUES($1, $2)`,
		},
		{
			// Pins the scan, not something the insert builder writes: an apostrophe-quoted text
			// that holds the clause end before the real one is read as inside the string.
			"apostrophe-quoted text holding the text before the clause",
			`INSERT INTO "t" ("id", 'x) VALUES (y') VALUES ($1, $2)`,
			`INSERT INTO "t" ("id", 'x) VALUES (y') OVERRIDING SYSTEM VALUE VALUES($1, $2)`,
		},
		{
			"value holding the text",
			`INSERT INTO "t" ("id", "label") VALUES (1, 'it''s a) VALUES (b')`,
			`INSERT INTO "t" ("id", "label") OVERRIDING SYSTEM VALUE VALUES(1, 'it''s a) VALUES (b')`,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			require.Equal(t, c.expected, BuildPgInsertIdentityAlwaysSql(c.input))
		})
	}
}

// Rows without a column give no value to override: the statement is returned as it is.
func Test_BuildPgInsertIdentityAlwaysSql_WithoutColumnList(t *testing.T) {
	for _, statement := range []string{
		`INSERT INTO "app"."users" DEFAULT VALUES ON CONFLICT DO NOTHING`,
		`INSERT INTO "a) VALUES (b" DEFAULT VALUES`,
	} {
		require.Equal(t, statement, BuildPgInsertIdentityAlwaysSql(statement))
	}
}

// A generated column takes no value, stored or virtual (PostgreSQL 18); nor does an identity
// generated always. An identity by default does.
func Test_isColumnUpdateAllowed(t *testing.T) {
	require.True(t, isColumnUpdateAllowed("", ""))
	require.True(t, isColumnUpdateAllowed("d", ""))
	require.False(t, isColumnUpdateAllowed("a", ""))
	require.False(t, isColumnUpdateAllowed("", "s"))
	require.False(t, isColumnUpdateAllowed("", "v"))
}
